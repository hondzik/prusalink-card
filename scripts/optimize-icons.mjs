import fs from 'fs';
import path from 'path';
import { optimize } from 'svgo';

const iconsDir = path.resolve('./src/assets/icons/');

function findSvgFiles(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const entryPath = path.join(dir, entry.name);
    if (entry.isDirectory()) return findSvgFiles(entryPath);
    return entry.name.endsWith('.svg') ? [entryPath] : [];
  });
}

// Ikony se vkládají přímo do bundlu (HACS plugin doručuje jen jediný soubor z hacs.json `filename`,
// takže za běhu nelze nic dotahovat). Klíč = název souboru bez přípony, např. 'status_nozzle'.
// Oranžová z originálních SVG zůstává, bílá se mění na currentColor (viz níže); width/height se odstraňují,
// aby velikost řídilo CSS — rozměry určuje viewBox.
const inlineIcons = new Map();
const files = findSvgFiles(iconsDir).map((f) => path.relative(iconsDir, f));

for (const file of files) {
  const svgData = fs.readFileSync(path.join(iconsDir, file), 'utf8');
  const result = optimize(svgData, {
    multipass: true,
    plugins: [
      'preset-default',
      { name: 'removeAttrs', params: { attrs: ['width', 'height', 'shape-rendering', 'image-rendering'] } },
    ],
  });
  const key = file.split(path.sep).join('/').replace(/\.svg$/, '');
  // bílá (#fff / #ffffff) se mění na currentColor, aby ji ikony kreslily barvou textu motivu
  // (na světlém pozadí tmavou); oranžová zůstává
  inlineIcons.set(key, result.data.replace(/\r\n/g, '\n').replace(/>\s+</g, '><').replace(/#ffffff|#fff\b/gi, 'currentColor').trim());
  console.log(`✅ Optimized: ${file}`);
}

const generatedFile = path.resolve('./src/generated/icons.ts');
const body = [...inlineIcons.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([key, svg]) => `  ${JSON.stringify(key)}: ${JSON.stringify(svg)},`)
  .join('\n');

fs.mkdirSync(path.dirname(generatedFile), { recursive: true });
fs.writeFileSync(
  generatedFile,
  [
    '// GENERATED by scripts/optimize-icons.mjs from src/assets/icons/ — do not edit by hand.',
    '// Run `npm run build` (or `npm run optimize-icons`) to regenerate.',
    '',
    'export const ICONS: Record<string, string> = {',
    body,
    '};',
    '',
  ].join('\n'),
  'utf8',
);
console.log(`✅ Inlined ${inlineIcons.size} icons into src/generated/icons.ts`);
